import { constantTimeEqual, makeSignature } from 'better-auth/crypto';
import { MCP_OAUTH_LOOPBACK_REDIRECT_PATTERNS } from '@workspace/shared';

export const MCP_OAUTH_SCOPE = 'sparky:mcp';

export const DEFAULT_MCP_OAUTH_ALLOWED_REDIRECT_URIS = [
  'https://claude.ai/api/mcp/auth_callback',
  'https://claude.com/api/mcp/auth_callback',
  ...MCP_OAUTH_LOOPBACK_REDIRECT_PATTERNS,
] as const;

export interface McpOAuthAvailability {
  available: boolean;
  reason: string | null;
}

export type McpOAuthMetadataKind =
  'authorization' | 'resource' | 'unsupported-oidc';

function configuredPublicUrl(): string | null {
  const configured =
    process.env.BETTER_AUTH_URL || process.env.SPARKY_FITNESS_FRONTEND_URL;
  if (!configured) return null;

  const withScheme = configured.startsWith('http')
    ? configured
    : `https://${configured}`;
  return withScheme.replace(/\/$/, '');
}

function isLoopbackHostname(hostname: string): boolean {
  const ipv4Octets = hostname.split('.');
  const isIpv4Loopback =
    ipv4Octets.length === 4 &&
    ipv4Octets[0] === '127' &&
    ipv4Octets.every((octet) => /^\d+$/.test(octet) && Number(octet) <= 255);
  return hostname === 'localhost' || hostname === '[::1]' || isIpv4Loopback;
}

/** Reports whether the configured public MCP resource satisfies MCP URL rules. */
export function getMcpOAuthAvailability(): McpOAuthAvailability {
  const configured = configuredPublicUrl();
  if (!configured) {
    return {
      available: false,
      reason:
        'Set BETTER_AUTH_URL or SPARKY_FITNESS_FRONTEND_URL before enabling Remote MCP OAuth.',
    };
  }

  let url: URL;
  try {
    url = new URL(configured);
  } catch {
    return {
      available: false,
      reason:
        'Remote MCP OAuth requires a valid BETTER_AUTH_URL or SPARKY_FITNESS_FRONTEND_URL.',
    };
  }

  if (
    url.protocol !== 'https:' &&
    !(url.protocol === 'http:' && isLoopbackHostname(url.hostname))
  ) {
    return {
      available: false,
      reason:
        'Remote MCP OAuth requires public HTTPS. Plain HTTP is supported only for localhost or loopback development URLs.',
    };
  }

  return { available: true, reason: null };
}

function requireConfiguredPublicUrl(): string {
  const availability = getMcpOAuthAvailability();
  if (!availability.available) {
    throw new Error(availability.reason ?? 'Remote MCP OAuth is unavailable.');
  }
  return configuredPublicUrl() as string;
}

function canonicalizeOAuthQueryParams(params: URLSearchParams): string {
  return [...params.entries()]
    .sort(([keyA, valueA], [keyB, valueB]) => {
      // Keep this byte-for-byte compatible with Better Auth's signed-query
      // canonicalization. localeCompare() can order non-ASCII input
      // differently and would reject a signature generated by the provider.
      if (keyA < keyB) return -1;
      if (keyA > keyB) return 1;
      if (valueA < valueB) return -1;
      if (valueA > valueB) return 1;
      return 0;
    })
    .reduce((canonical, [key, value]) => {
      canonical.append(key, value);
      return canonical;
    }, new URLSearchParams())
    .toString();
}

/** Verifies the signed, expiring query emitted by Better Auth's OAuth plugin. */
export async function verifyMcpOAuthQuery(
  query: string,
  secret: string
): Promise<boolean> {
  const params = new URLSearchParams(query);
  const signatures = params.getAll('sig');
  const signature = signatures[0];
  const expiresAt = Number(params.get('exp'));
  params.delete('sig');
  if (
    signatures.length !== 1 ||
    !signature ||
    !Number.isFinite(expiresAt) ||
    expiresAt * 1000 < Date.now()
  ) {
    return false;
  }
  const expected = await makeSignature(
    canonicalizeOAuthQueryParams(params),
    secret
  );
  return constantTimeEqual(signature, expected);
}

/** Public origin used by clients to reach SparkyFitness. */
export function getPublicOrigin(): string {
  return new URL(requireConfiguredPublicUrl()).origin;
}

/** Canonical RFC 8707 resource identifier for the remote MCP endpoint. */
export function getMcpResourceUrl(): string {
  return new URL('/mcp', getPublicOrigin()).toString();
}

/** Better Auth OAuth issuer, including its configured base path. */
export function getOAuthIssuerUrl(): string {
  return new URL('/api/auth', getPublicOrigin()).toString();
}

/** RFC 9728 metadata URL for the canonical MCP resource. */
export function getMcpResourceMetadataUrl(): string {
  return new URL(
    '/.well-known/oauth-protected-resource/mcp',
    getPublicOrigin()
  ).toString();
}

/** Local JWKS endpoint used to avoid public-DNS and reverse-proxy hairpinning. */
export function getMcpLoopbackJwksUrl(): string {
  const port = process.env.SPARKY_FITNESS_SERVER_PORT || '3010';
  return `http://127.0.0.1:${port}/api/auth/jwks`;
}

/** Matches exact redirect URIs and the explicit loopback-any-port patterns. */
export function isMcpOAuthRedirectUriAllowed(
  redirectUri: string,
  allowedRedirectUris: readonly string[]
): boolean {
  if (allowedRedirectUris.includes(redirectUri)) return true;

  let url: URL;
  try {
    url = new URL(redirectUri);
  } catch {
    return false;
  }

  if (url.protocol !== 'http:' || !isLoopbackHostname(url.hostname)) {
    return false;
  }

  const pattern = `http://${url.hostname}:*`;
  return allowedRedirectUris.includes(pattern);
}

/**
 * Builds Better Auth's authorization-time redirect validator. The provider's
 * own match must succeed first, then the administrator's current allowlist is
 * rechecked using the provider-parsed redirect URI.
 */
export function createMcpOAuthAuthorizationRedirectValidator(
  getAllowedRedirectUris: () => Promise<string[]>
) {
  return async (
    redirectUri: string,
    _registeredUris: readonly string[],
    defaultResult: boolean
  ): Promise<boolean> => {
    if (!defaultResult) return false;
    const allowedRedirectUris = await getAllowedRedirectUris();
    return isMcpOAuthRedirectUriAllowed(redirectUri, allowedRedirectUris);
  };
}

/** Identifies Better Auth routes that must stay dark while MCP OAuth is off. */
export function isMcpOAuthAuthEndpointPath(requestPath: string): boolean {
  return (
    requestPath === '/api/auth/oauth2' ||
    requestPath.startsWith('/api/auth/oauth2/') ||
    requestPath === '/api/auth/admin/oauth2' ||
    requestPath.startsWith('/api/auth/admin/oauth2/') ||
    requestPath === '/api/auth/jwks' ||
    requestPath === '/api/auth/oauth-consent-details' ||
    requestPath.includes('/.well-known/oauth-authorization-server') ||
    requestPath.includes('/.well-known/openid-configuration')
  );
}

/** Classifies the public OAuth metadata probes, including /mcp-prefixed forms. */
export function classifyMcpOAuthMetadataPath(
  requestPath: string
): McpOAuthMetadataKind | null {
  const path = requestPath.startsWith('/mcp/.well-known/')
    ? requestPath.slice('/mcp'.length)
    : requestPath;

  if (path === '/.well-known/openid-configuration') {
    return 'unsupported-oidc';
  }

  if (
    path === '/.well-known/oauth-authorization-server' ||
    path === '/.well-known/oauth-authorization-server/api/auth' ||
    path === '/api/auth/.well-known/oauth-authorization-server'
  ) {
    return 'authorization';
  }

  if (
    path === '/.well-known/oauth-protected-resource' ||
    path === '/.well-known/oauth-protected-resource/mcp'
  ) {
    return 'resource';
  }

  return null;
}

/** Returns whether a metadata probe must retain the API-key-only 404 response. */
export function shouldReturnMcpOAuthMetadataNotFound(
  requestPath: string,
  oauthEnabled: boolean,
  oauthAvailable: boolean
): boolean {
  const kind = classifyMcpOAuthMetadataPath(requestPath);
  return (
    kind === 'unsupported-oidc' ||
    (kind !== null && (!oauthEnabled || !oauthAvailable))
  );
}
