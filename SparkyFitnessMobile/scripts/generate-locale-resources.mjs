#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

export function renderLocaleResourceModule(registry) {
  const locales = Object.keys(registry.locales).sort();
  const imports = locales
    .map(
      (locale) =>
        `import ${identifier(locale)}Translation from './locales/${locale}/translation.json';`
    )
    .join('\n');
  const entries = locales
    .map(
      (locale) =>
        `  ${JSON.stringify(locale)}: { translation: ${identifier(locale)}Translation },`
    )
    .join('\n');
  return `/**\n * GENERATED by scripts/generate-locale-resources.mjs from localeRegistry.json.\n * Do not edit by hand; run pnpm run i18n:generate.\n */\nimport type { SupportedLanguage } from './localeRegistry';\n${imports}\n\nexport const RESOURCE_MAP = {\n${entries}\n} satisfies Record<SupportedLanguage, { translation: object }>;\n`;
}

export function validateShippedLocaleFiles({ root, registry }) {
  for (const locale of Object.keys(registry.locales)) {
    for (const relativePath of [
      `src/localization/locales/${locale}/translation.json`,
      `locales/${locale}.json`,
    ]) {
      if (!fs.existsSync(path.join(root, relativePath))) {
        throw new Error(
          `[i18n:generate] Shipped locale "${locale}" is missing ${relativePath}`
        );
      }
    }
  }
}

function identifier(locale) {
  return `locale_${locale.replaceAll(/[^A-Za-z0-9_$]/g, '_')}`;
}
function argumentValue(name, fallback) {
  const index = process.argv.indexOf(name);
  return index === -1 ? fallback : path.resolve(process.argv[index + 1]);
}
function main() {
  const root = argumentValue('--root', path.resolve(import.meta.dirname, '..'));
  const registryPath = argumentValue(
    '--registry',
    path.join(root, 'src/localization/localeRegistry.json')
  );
  const outputPath = argumentValue(
    '--output',
    path.join(root, 'src/localization/generatedLocaleResources.ts')
  );
  const check = process.argv.includes('--check');
  const registry = JSON.parse(fs.readFileSync(registryPath, 'utf8'));
  validateShippedLocaleFiles({ root, registry });
  const output = renderLocaleResourceModule(registry);
  if (check) {
    if (
      !fs.existsSync(outputPath) ||
      fs.readFileSync(outputPath, 'utf8') !== output
    ) {
      throw new Error(
        '[i18n:generate] generatedLocaleResources.ts is stale; run pnpm run i18n:generate'
      );
    }
    console.log('[i18n:generate] generated locale resources are current');
  } else {
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, output, 'utf8');
    console.log(
      `[i18n:generate] generated ${path.relative(root, outputPath)} for ${Object.keys(registry.locales).sort().join(', ')}`
    );
  }
}
if (
  process.argv[1] &&
  import.meta.url === new URL(`file://${process.argv[1]}`).href
)
  main();
