import { z } from 'zod';

export const coachNudgesSchema = z.object({
  id: z.string(),
  user_id: z.string(),
  coach_id: z.string(),
  local_day: z.coerce.date(),
  checkin_slot: z.string(),
  rule_key: z.string(),
  because: z.unknown(),
  source: z.string(),
  template_key: z.string().nullable(),
  template_params: z.unknown().nullable(),
  chat_message_id: z.string(),
  read_at: z.coerce.date().nullable(),
  kind: z.string(),
  reaction: z.number().nullable(),
  reaction_at: z.coerce.date().nullable(),
  suggestion: z.unknown().nullable(),
  suggestion_status: z.string().nullable(),
  suggestion_resolved_at: z.coerce.date().nullable(),
  question: z.string().nullable(),
  question_ref: z.string().nullable(),
  answer: z.unknown().nullable(),
  answered_at: z.coerce.date().nullable(),
  exercise_entry_id: z.string().nullable(),
  created_at: z.coerce.date(),
});

